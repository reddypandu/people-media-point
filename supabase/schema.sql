-- Initial Districts (Telangana)
DO $$
DECLARE
  telangana_id BIGINT;
BEGIN
  SELECT id INTO telangana_id FROM categories WHERE name = 'Telangana';

  INSERT INTO districts (name, category_id)
  SELECT v.name, telangana_id
  FROM (
    VALUES
      ('Hyderabad'),
      ('Karimnagar'),
      ('Nalgonda'),
      ('Adilabad'),
      ('Nizamabad'),
      ('Mahabubnagar'),
      ('Warangal'),
      ('Khammam'),
      ('Medak')
  ) AS v(name)
  WHERE NOT EXISTS (
    SELECT 1 FROM districts d WHERE d.name = v.name AND d.category_id = telangana_id
  );
END $$;

